// Only repetitive framework declarations are generated. Native behavior lives in components/.
const root = fileURLToPath(new URL('../packages/nativescript/src/', import.meta.url))
const check = process.argv.includes('--check')
async function write(file, value) {
  if (file.endsWith('.ts')) value = await format(value, { ...await resolveConfig(root), parser: 'typescript' })
  if (check) {
    if (await readFile(path.join(root, file), 'utf8') !== value)
      throw new Error(`${file} is stale; run npm run adapters:generate`)
  } else {
    await mkdir(path.dirname(path.join(root, file)), { recursive: true })
    await writeFile(path.join(root, file), value)
  }
}
