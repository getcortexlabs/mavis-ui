import { mkdirSync, copyFileSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'

// Regenerates the icon map and font files from lucide-static. Run after upgrading the package.
const require = createRequire(import.meta.url)
const root = resolve(import.meta.dirname, '..')
const source = dirname(require.resolve('lucide-static/package.json'))
const { version } = JSON.parse(readFileSync(resolve(source, 'package.json'), 'utf8'))
const info = JSON.parse(readFileSync(resolve(source, 'font/info.json'), 'utf8'))
const canonical = Object.keys(JSON.parse(readFileSync(resolve(source, 'icon-nodes.json'), 'utf8')))
const names = canonical.filter((name) => info[name]).sort()
const entries = names.map(
  (name) =>
    `  '${name}': 0x${parseInt(info[name].encodedCode.replace(/^\\/, ''), 16).toString(16)},`,
)
writeFileSync(
  resolve(root, 'packages/core/src/icons.ts'),
  `// Generated by scripts/generate-icons.mjs from lucide-static ${version} (ISC). Do not edit by hand.\nexport const iconFontVersion = '${version}'\nexport const icons = {\n${entries.join('\n')}\n} as const\n`,
)
const license = `Lucide icon font ${version}\n\n${readFileSync(resolve(source, 'LICENSE'), 'utf8')}`
for (const [file, target] of [
  ['font/lucide.ttf', 'packages/nativescript/fonts/lucide.ttf'],
  ['font/lucide.woff2', 'packages/web/src/fonts/lucide.woff2'],
]) {
  mkdirSync(dirname(resolve(root, target)), { recursive: true })
  copyFileSync(resolve(source, file), resolve(root, target))
  writeFileSync(resolve(dirname(resolve(root, target)), 'LICENSE'), license)
}
console.log(`${names.length} icons from lucide-static ${version}`)
