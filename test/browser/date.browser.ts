import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('keeps exact drafts and navigates the calendar by day, week, month and year before committing', async ({
  page,
}) => {
  await page.goto('/playground/#/checks/date')
  const input = page.locator('#single-date')
  await input.fill('2024-02-')
  await expect(input).toHaveValue('2024-02-')
  await expect(page.getByText('Single: 2024-02-29', { exact: true })).toBeVisible()
  await input.fill('02/03/2024')
  await input.blur()
  await expect(input).toHaveValue('02/03/2024')
  await expect(input).toHaveAttribute('aria-invalid', 'true')
  await input.fill('2024-02-29')
  const opener = page.getByRole('button', { name: 'Choose date: Departure', exact: true })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: 'Departure', exact: true })
  const day = (date: string) => dialog.locator(`[data-date="${date}"]`)
  await expect(day('2024-02-29')).toBeFocused()
  await expect(dialog.getByRole('button', { name: 'Previous month' })).toBeDisabled()
  await day('2024-02-29').press('PageDown')
  await expect(day('2024-03-29')).toBeFocused()
  await day('2024-03-29').press('Shift+PageDown')
  await expect(day('2025-03-29')).toBeFocused()
  await expect(dialog.getByRole('button', { name: 'Next month' })).toBeDisabled()
  await day('2025-03-29').press('Shift+PageUp')
  await expect(day('2024-03-29')).toBeFocused()
  await day('2024-03-29').press('Home')
  await expect(day('2024-03-25')).toBeFocused()
  await day('2024-03-25').press('End')
  await expect(day('2024-03-31')).toBeFocused()
  await day('2024-03-31').press('ArrowRight')
  await expect(day('2024-04-01')).toBeFocused()
  await expect(page.getByText('Single: 2024-02-29', { exact: true })).toBeVisible()
  await day('2024-04-01').press('Enter')
  await expect(dialog).toBeHidden()
  await expect(input).toHaveValue('2024-04-01')
  await expect(opener).toBeFocused()
  await opener.press('Enter')
  await expect(day('2024-04-01')).toBeFocused()
  await day('2024-04-01').press('ArrowDown')
  await day('2024-04-08').press('Escape')
  await expect(dialog).toBeHidden()
  await expect(opener).toBeFocused()
  await expect(input).toHaveValue('2024-04-01')
})

test('range editing preserves invalid ordering and blocked interior drafts, permits partial and equal endpoints', async ({
  page,
}) => {
  await page.goto('/playground/#/checks/date')
  const start = page.locator('#travel-range-start')
  const end = page.locator('#travel-range-end')
  await end.fill('2024-03-11')
  await expect(end).toHaveValue('2024-03-11')
  await expect(
    page.getByText('This range includes an unavailable date.', { exact: true }),
  ).toBeVisible()
  await expect(page.getByText('Range: 2024-03-09 / 2024-03-09', { exact: true })).toBeVisible()
  await start.fill('2024-03-12')
  await expect(
    page.getByText('The end must be on or after the start.', { exact: true }),
  ).toBeVisible()
  await expect(start).toHaveValue('2024-03-12')
  await expect(end).toHaveValue('2024-03-11')
  await end.fill('2024-03-12')
  await expect(page.getByText('Range: 2024-03-12 / 2024-03-12', { exact: true })).toBeVisible()
  await start.fill('')
  await expect(page.getByText('Range: empty / 2024-03-12', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Clear dates: Journey', exact: true }).click()
  await expect(start).toHaveValue('')
  await expect(end).toHaveValue('')
  await expect(page.getByText('Range: empty / empty', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Choose date: Journey · Start', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Journey · Start', exact: true })
  await expect(dialog.locator('[data-date="2024-03-01"]')).toBeFocused()
  const unavailable = dialog.locator('[data-date="2024-03-10"]')
  await unavailable.focus()
  await expect(unavailable).toHaveAttribute('aria-disabled', 'true')
  await unavailable.press('Enter')
  await expect(dialog).toBeVisible()
  await expect(page.getByText('Range: empty / empty', { exact: true })).toBeVisible()
  await unavailable.press('ArrowRight')
  await dialog.locator('[data-date="2024-03-11"]').press('Space')
  await expect(dialog).toBeHidden()
  await expect(start).toHaveValue('2024-03-11')
})

test('honors external bounds, readonly, disabled, rejection and deterministic locale without rewriting model', async ({
  page,
}) => {
  await page.goto('/playground/#/checks/date')
  const input = page.locator('#single-date')
  await page.locator('#rejected-date').fill('2024-03-03')
  await expect(page.locator('#rejected-date')).toHaveValue('2024-02-01')
  await expect(page.getByText('Requests: 1', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Choose date: Departure', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Departure', exact: true })
  await page.locator('#date-bound').evaluate((element: HTMLElement) => element.click())
  await expect(dialog.locator('[data-date="2024-02-20"]')).toBeFocused()
  await expect(dialog.getByRole('button', { name: 'Next month' })).toBeDisabled()
  await expect(input).toHaveValue('2024-02-29')
  await page.locator('#date-readonly').evaluate((element: HTMLElement) => element.click())
  await expect(dialog).toBeHidden()
  await expect(input).toHaveAttribute('readonly', '')
  await expect(
    page.getByRole('button', { name: 'Choose date: Departure', exact: true }),
  ).toBeDisabled()
  await page.locator('#date-readonly').click()
  await page.locator('#date-external').click()
  await expect(input).toHaveValue('2024-02-14')
  await page.locator('#date-locale').click()
  await expect(input).toHaveAttribute('placeholder', 'AAAA-MM-DD')
  await page.getByRole('button', { name: 'Escolher data: Departure', exact: true }).click()
  await expect(dialog.getByRole('grid', { name: 'fevereiro 2024' })).toBeVisible()
  await page.locator('#date-disable').evaluate((element: HTMLElement) => element.click())
  await expect(dialog).toBeHidden()
  await expect(input).toBeDisabled()
  await page.getByRole('button', { name: 'Choose date: Empty date', exact: true }).click()
  await expect(page.getByRole('grid', { name: 'January 2000' })).toBeVisible()
})

test('keeps narrow calendars scrollable, one grid Tab stop, accessible associations and focus on unmount', async ({
  page,
}) => {
  await page.setViewportSize({ width: 320, height: 844 })
  await page.goto('/playground/#/checks/date')
  const opener = page.getByRole('button', { name: 'Choose date: Departure', exact: true })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: 'Departure', exact: true })
  await expect(dialog.locator('table button[tabindex="0"]')).toHaveCount(1)
  await expect(dialog.locator('th').first()).toHaveAttribute('abbr', 'Monday')
  await expect
    .poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    .toBe(true)
  const overflow = await dialog
    .locator('.m-date-calendar')
    .evaluate((element) => ({ width: element.clientWidth, content: element.scrollWidth }))
  expect(overflow.width).toBeLessThanOrEqual(320)
  expect(overflow.content).toBeGreaterThan(overflow.width)
  const results = await new AxeBuilder({ page }).include('dialog[open]').analyze()
  expect(results.violations).toEqual([])
  await page.locator('#date-unmount').evaluate((element: HTMLElement) => element.click())
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('#single-date')).toHaveCount(0)
  await expect(page.locator('body')).not.toHaveAttribute('inert', '')
})

test('keeps Tab and Shift+Tab inside the Sheet when the roving calendar day is midmonth', async ({
  page,
  browserName,
}) => {
  await page.goto('/playground/#/checks/date')
  await page.getByRole('button', { name: 'Choose date: Departure', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Departure', exact: true })
  await dialog.locator('[data-date="2024-02-29"]').press('PageDown')
  const active = dialog.locator('[data-date="2024-03-29"]')
  await expect(active).toBeFocused()
  await expect(dialog.locator('[data-date="2024-03-31"]')).toHaveAttribute('tabindex', '-1')
  const tab = browserName === 'webkit' && process.platform === 'darwin' ? 'Alt+Tab' : 'Tab'
  const close = dialog.getByRole('button', { name: 'Close', exact: true })
  const handle = dialog.getByRole('slider')
  await active.press(tab)
  await expect(handle).toBeFocused()
  await handle.press(tab)
  await expect(close).toBeFocused()
  await close.press(`Shift+${tab}`)
  await expect(handle).toBeFocused()
  await handle.press(`Shift+${tab}`)
  await expect(active).toBeFocused()
  await active.press(`Shift+${tab}`)
  await expect(dialog.getByRole('button', { name: 'Next month' })).toBeFocused()
  await dialog.getByRole('button', { name: 'Next month' }).press(tab)
  await expect(active).toBeFocused()
})

test('preserves the draft across Mavis and Midnight and keeps the dark calendar accessible', async ({
  page,
}) => {
  await page.goto('/playground/#/components/date-picker')
  const input = page.getByRole('textbox', { name: 'Dia do encontro', exact: true })
  await input.fill('12/11/')
  const before = await input.evaluate((element) => getComputedStyle(element).backgroundColor)
  await page.getByRole('button', { name: 'Trocar tema', exact: true }).click()
  await expect(input).toHaveValue('12/11/')
  await expect
    .poll(() => input.evaluate((element) => getComputedStyle(element).backgroundColor))
    .not.toBe(before)
  await page.getByRole('button', { name: 'Escolher data: Dia do encontro', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Dia do encontro', exact: true })
  await expect(dialog.getByRole('grid', { name: 'novembro 2026', exact: true })).toBeVisible()
  await expect(dialog.locator('[data-date="2026-11-15"]')).toHaveAttribute('aria-disabled', 'true')
  const results = await new AxeBuilder({ page }).include('dialog[open]').analyze()
  expect(results.violations).toEqual([])
  await dialog.locator('[data-date="2026-11-12"]').click()
  await expect(dialog).toBeHidden()
  await expect(input).toHaveValue('12/11/2026')
  await expect(page.getByText('Data escolhida: 2026-11-12', { exact: true })).toBeVisible()
})
