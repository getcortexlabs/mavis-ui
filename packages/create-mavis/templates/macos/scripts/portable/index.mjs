import { createHash } from 'node:crypto'
import { readdir, readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { createProgram, prelude } from './program.mjs'
import { buildModel, PortableError } from './model.mjs'
import { emitVue, emitVueTypes } from './emit-vue.mjs'
import { SwiftEmitter, runtime, themeTokens } from './emit-swift.mjs'

export { PortableError }
export const compilerName = 'Mavis portable compiler (experimental)'

const sha = (text) => createHash('sha256').update(text).digest('hex')

/** Component (Name.lite.tsx) and type (name.ts) files from a project's shared folder. */
export async function readShared(projectRoot) {
  const files = new Map()
  for (const name of (await readdir(join(projectRoot, 'shared'))).sort())
    if (/\.lite\.tsx$/.test(name) || (/\.ts$/.test(name) && !/\.d\.ts$/.test(name)))
      files.set(`shared/${name}`, await readFile(join(projectRoot, 'shared', name), 'utf8'))
  return files
}

/**
 * Checks the shared sources and produces Vue and SwiftUI files. Nothing is written
 * here; callers replace generated files only after the whole project compiled.
 *
 * files: Map<'shared/Name.lite.tsx' | 'shared/types.ts', source text>
 */
export async function compileProject(files, { theme = 'mavis', root = 'Welcome', namespace } = {}) {
  const core = await import('@getcortexlabs/mavis-core')
  if (!['mavis', 'midnight'].includes(theme)) throw new PortableError('Unknown starter theme.')
  const tokenTheme = core[theme]
  for (const path of files.keys())
    if (!/^shared\/([A-Z][A-Za-z0-9]*\.lite\.tsx|[a-z][A-Za-z0-9]*\.ts)$/.test(path))
      throw new PortableError(
        `${path}: Shared files are Name.lite.tsx components or lowercase .ts type files.`,
      )
  const program = createProgram(files, tokenTheme)
  if (program.diagnostics.length) throw new PortableError(program.diagnostics.join('\n'))
  const model = buildModel(program, [...files.keys()].sort())
  const names = new Set(model.components.map((component) => component.name))
  if (!names.has(root))
    throw new PortableError(`shared/${root}.lite.tsx: The root component ${root} is missing.`)
  for (const record of model.records)
    if (names.has(record.name))
      throw new PortableError(`${record.name} is both a record type and a component; rename one.`)

  const header = (path) =>
    `Generated by the ${compilerName} from ${path} (sha256 ${sha(files.get(path))}). Do not edit.`
  const typesHeader = `Generated by the ${compilerName}; types from ${[...files.keys()].sort().join(', ')}. Do not edit.`
  const vue = new Map()
  const swift = new Map()
  const swiftEmitter = new SwiftEmitter(model)
  const { tokens, source: tokenSource } = themeTokens(tokenTheme)
  for (const component of model.components) {
    vue.set(`${component.name}.vue`, emitVue(component, header(component.path)))
    swift.set(
      `${component.name}.swift`,
      swiftEmitter.component(component, tokens, header(component.path), namespace),
    )
  }
  vue.set('types.ts', emitVueTypes(model.records, typesHeader))
  swift.set('MavisTypes.swift', swiftEmitter.types(model.records, typesHeader, namespace))
  swift.set('MavisRuntime.swift', `// Generated by the ${compilerName}. Do not edit.\n${runtime}`)
  swift.set(
    'MavisTokens.swift',
    `// Generated by the ${compilerName} for the ${theme} theme. Do not edit.\n${tokenSource}`,
  )
  // Ambient types so editors check shared/ the same way (see tsconfig.json).
  return { model, vue, swift, environment: prelude(tokenTheme) }
}
