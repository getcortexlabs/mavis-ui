export function statusLabel(id, pt = false) {
  const status = componentUpdates[id]
  return status === 'new'
    ? pt
      ? 'Novo'
      : 'New'
    : status === 'updated'
      ? pt
        ? 'Atualizado'
        : 'Updated'
      : ''
}
export function statusDescription(id, pt = false) {
  if (!componentUpdates[id]) return ''
  return `${statusLabel(id, pt)} · Mavis 0.1.0-rc.12`
}
